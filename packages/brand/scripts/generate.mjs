// Generates tokens.css, the logo SVGs and every raster icon from src/tokens.ts and src/logo.ts, writing the app
// assets in place so the web app, the landing page and the mobile app never drift. Run: pnpm --filter @taskop/brand generate
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import sharp from 'sharp';
import { dark, light } from '../dist/tokens.js';
import { markSvg, tileSvg, wordmarkSvg } from '../dist/logo.js';

const root = join(import.meta.dirname, '..', '..', '..');
const pkg = join(import.meta.dirname, '..');
const out = async (file, data) => {
  await mkdir(dirname(file), { recursive: true });
  await writeFile(file, data);
  console.log('wrote', file.replace(root + '/', ''));
};
const png = async (svg, size, file, opts = {}) => {
  const buf = await sharp(Buffer.from(svg), { density: 384 }).resize(size, size, opts).png().toBuffer();
  await out(file, buf);
  return buf;
};

// ---- tokens.css: --tp-* custom properties, light on :root, dark under .dark and [data-theme="dark"] ----
const vars = (t) => {
  const lines = [];
  for (const [k, v] of Object.entries(t)) {
    if (k === 'status') for (const [s, sv] of Object.entries(v)) for (const [step, c] of Object.entries(sv)) lines.push(`  --tp-${s}-${step}: ${c};`);
    else lines.push(`  --tp-${k.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase())}: ${v};`);
  }
  return lines.join('\n');
};
const css = `/* Generated by packages/brand/scripts/generate.mjs from src/tokens.ts. Do not edit by hand. */
:root {
${vars(light)}
  --tp-radius-control: 10px;
  --tp-radius-card: 14px;
  --tp-radius-chip: 6px;
  --tp-radius-sheet: 20px;
  --tp-shadow-card: 0 1px 0 rgb(22 34 53 / 0.04), 0 0 0 1px var(--tp-line);
  --tp-shadow-raised: 0 1px 2px rgb(2 27 43 / 0.08), 0 8px 24px -8px rgb(2 27 43 / 0.18), 0 0 0 1px var(--tp-line);
  --tp-font: 'IBM Plex Sans', 'IBM Plex Sans Variable', system-ui, -apple-system, 'Segoe UI', sans-serif;
  color-scheme: light;
}
.dark,
[data-theme='dark'] {
${vars(dark)}
  --tp-shadow-card: 0 0 0 1px var(--tp-line);
  --tp-shadow-raised: 0 8px 24px -8px rgb(0 0 0 / 0.6), 0 0 0 1px var(--tp-line-strong);
  color-scheme: dark;
}
`;
await out(join(pkg, 'tokens.css'), css);
// For pages without a theme switch (the landing page): the dark tokens follow the system preference.
await out(
  join(pkg, 'tokens-system.css'),
  `/* Generated by packages/brand/scripts/generate.mjs. Dark tokens under prefers-color-scheme, for pages without a theme switch. */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${vars(dark)}
    --tp-shadow-card: 0 0 0 1px var(--tp-line);
    --tp-shadow-raised: 0 8px 24px -8px rgb(0 0 0 / 0.6), 0 0 0 1px var(--tp-line-strong);
    color-scheme: dark;
  }
}
`,
);

// ---- logo SVGs ----
const L = light;
await out(join(pkg, 'logo', 'mark.svg'), markSvg());
await out(join(pkg, 'logo', 'mark-caspian.svg'), markSvg({ color: L.primary }));
await out(join(pkg, 'logo', 'wordmark.svg'), wordmarkSvg({ color: L.ink, markColor: L.primary }));
await out(join(pkg, 'logo', 'wordmark-white.svg'), wordmarkSvg({ color: '#FFFFFF' }));
await out(join(pkg, 'logo', 'tile.svg'), tileSvg({ background: L.primary, color: '#FFFFFF', radius: 0.22 }));
await out(join(pkg, 'logo', 'tile-deep-saffron.svg'), tileSvg({ background: L.deep, color: L.saffron, radius: 0.22 }));

// ---- favicons for the web app and the landing page ----
const favicon = tileSvg({ background: L.primary, color: '#FFFFFF', radius: 0.22 });
const touch = tileSvg({ background: L.primary, color: '#FFFFFF', radius: 0 });
for (const app of ['web', 'landing']) {
  const dir = join(root, 'apps', app, 'public');
  await out(join(dir, 'favicon.svg'), favicon);
  const p16 = await png(favicon, 16, join(dir, 'favicon-16.png'));
  const p32 = await png(favicon, 32, join(dir, 'favicon-32.png'));
  const p48 = await png(favicon, 48, join(dir, 'favicon-48.png'));
  await out(join(dir, 'favicon.ico'), ico([p16, p32, p48]));
  await png(touch, 180, join(dir, 'apple-touch-icon.png'));
  await png(favicon, 192, join(dir, 'icon-192.png'));
  await png(favicon, 512, join(dir, 'icon-512.png'));
  // Maskable: the mark inside the 80% safe zone of a square tile.
  await png(tileSvg({ background: L.primary, color: '#FFFFFF', radius: 0, scale: 0.5 }), 512, join(dir, 'icon-maskable-512.png'));
}

